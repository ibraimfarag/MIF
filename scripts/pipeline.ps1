<#
.SYNOPSIS
    The one entry point for every check MI CS runs - locally and in CI.

.DESCRIPTION
    Before this script existed the same commands lived in three places: AGENTS.md's
    "four checks", the CI workflow, and the hand-typed lines in every session's
    notes. They drifted (CI ran `flutter analyze --fatal-infos` without `--no-pub`,
    AGENTS.md ran with it), so a green local run and a red CI run could both be
    "correct". This file is now the only place the order and the flags live; the
    workflow calls it, and so does a human.

    Tiers:
      fast     what must be green before every commit (the four checks).
      full     fast + the release builds, so packaging is never the first place
               a compile error appears.
      release  full + the artifact verifiers, one per slice as they land
               (today: opsec and the package manifest; hardening and release
               already run inside make-release.ps1 / verify-release.ps1). Needs a
               packaged `dist` artifact.

    Every step is one command with one working directory, and a failure stops the
    run immediately: the report names the step that failed instead of hiding it
    behind three later failures.

.PARAMETER Tier
    fast (default), full or release.

.PARAMETER Only
    Run just the steps whose id matches this wildcard (e.g. -Only 'engine.*').
    Meant for the inner loop; it does not change a step's own flags.

.PARAMETER CargoTargetDir
    Sets CARGO_TARGET_DIR for the run. The repo's own instructions use
    "$env:TEMP\mics-target" when `engine\target` is not writable; CI leaves it
    empty so its cache can key on the default path.

.PARAMETER List
    Print the steps for the selected tier and exit without running anything.

.EXAMPLE
    pwsh ./scripts/pipeline.ps1

.EXAMPLE
    pwsh ./scripts/pipeline.ps1 -Tier full -CargoTargetDir "$env:TEMP\mics-target"
#>
[CmdletBinding()]
param(
    [ValidateSet('fast', 'full', 'release')]
    [string]$Tier = 'fast',

    [string]$Only = '',

    [string]$CargoTargetDir = '',

    [switch]$List
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repo = Split-Path -Parent $PSScriptRoot
$tierRank = @{ fast = 0; full = 1; release = 2 }
$limit = $tierRank[$Tier]

# ---------------------------------------------------------------- environment

if ($CargoTargetDir) {
    $env:CARGO_TARGET_DIR = $CargoTargetDir
    Write-Output "CARGO_TARGET_DIR=$CargoTargetDir"
}

# The YARA rules pack is regenerated by the build script; letting `cargo test`
# regenerate it rewrites a tracked file mid-run and turns a green tree dirty.
$env:YRX_REGENERATE_MODULES_RS = 'false'

Push-Location $repo
try {
    $head = (& git rev-parse --short HEAD) 2>$null
    if (-not $head) { $head = 'unknown' }
} finally {
    Pop-Location
}

Write-Output "MI CS pipeline - tier=$Tier head=$head"

# Flutter needs a resolved package config; `--no-pub` everywhere else is what
# keeps the measured run from mutating the tree.
$packageConfig = Join-Path $repo '.dart_tool\package_config.json'
if (-not (Test-Path $packageConfig)) {
    Write-Output '==> flutter pub get (no package_config.json yet)'
    Push-Location $repo
    try {
        & flutter pub get
        if ($LASTEXITCODE -ne 0) { throw 'flutter pub get failed' }
    } finally {
        Pop-Location
    }
}

# -------------------------------------------------------------------- the steps

$steps = @(
    @{
        Id   = 'flutter.analyze'
        Tier = 'fast'
        Dir  = $repo
        Run  = { flutter analyze --no-pub --fatal-infos }
        What = 'Dart analysis, infos are failures'
    },
    @{
        Id   = 'flutter.test'
        Tier = 'fast'
        Dir  = $repo
        Run  = { flutter test --no-pub }
        What = 'Widget, model, i18n and contrast tests'
    },
    @{
        Id   = 'engine.test'
        Tier = 'fast'
        Dir  = Join-Path $repo 'engine'
        Run  = { cargo test }
        What = 'Rust unit and integration tests'
    },
    @{
        Id   = 'engine.clippy'
        Tier = 'fast'
        Dir  = Join-Path $repo 'engine'
        Run  = { cargo clippy --release -- -D warnings }
        What = 'Clippy with zero warnings allowed'
    },
    @{
        Id   = 'engine.build'
        Tier = 'full'
        Dir  = Join-Path $repo 'engine'
        Run  = {
            # A release build that is meant to be shipped must not name this
            # machine's user. rustc records the source directory of every
            # dependency, which by default is `%USERPROFILE%\.cargo\registry\...`;
            # `engine-rustflags.ps1` appends the remap to the crate's own flags,
            # because `CARGO_ENCODED_RUSTFLAGS` overrides `.cargo\config.toml`
            # rather than adding to it (remapping by hand cost the engine its CFG
            # table, caught by the hardening gate on 2026-11-02). So `-Tier full`
            # builds the same clean binary `make-release.ps1` packages.
            . (Join-Path $repo 'scripts\engine-rustflags.ps1')
            $env:CARGO_ENCODED_RUSTFLAGS = Get-EngineRustFlags -Repo $repo
            cargo build --release
        }
        What = 'Release build of the engine'
    },
    @{
        Id   = 'engine.smoke'
        Tier = 'full'
        Dir  = Join-Path $repo 'engine'
        Run  = {
            # The binary, not the crate: a release build that starts and answers
            # its own CLI is the cheapest proof that linking did not break.
            if ($env:CARGO_TARGET_DIR) {
                $exe = Join-Path $env:CARGO_TARGET_DIR 'release\mics-engine.exe'
            } else {
                $exe = Join-Path (Get-Location) 'target\release\mics-engine.exe'
            }
            & $exe benchmark
        }
        What = 'The built engine starts and runs its own benchmark'
    },
    @{
        Id   = 'engine.lifecycle'
        Tier = 'full'
        Dir  = $repo
        Run  = {
            # D-039's engine half, against the release binary: the engine ends
            # when the app that started it does, answers `shutdown` before it
            # ends, and leaves alone an engine nobody owns. It starts its own
            # isolated engines on private pipes, so the fast tier's unit tests
            # cannot see any of this.
            $engineArgs = @("-NoProfile", "-ExecutionPolicy", "Bypass",
                "-File", (Join-Path $repo 'scripts\verify-lifecycle.ps1'))
            if ($env:CARGO_TARGET_DIR) {
                $engineArgs += @("-EngineExe", (Join-Path $env:CARGO_TARGET_DIR 'release\mics-engine.exe'))
            }
            powershell @engineArgs
            if ($LASTEXITCODE -ne 0) { throw "verify-lifecycle.ps1 exited $LASTEXITCODE" }
        }
        What = 'The engine ends with the app that started it, and answers a shutdown first'
    },
    @{
        Id   = 'engine.contract'
        Tier = 'full'
        Dir  = $repo
        Run  = {
            # The dispatcher's whole surface, against the release binary in a
            # throw-away data dir: every method answers in its documented shape,
            # every malformed call is refused, and the engine is still serving
            # at the end. qa/methods.json is the list; test/qa_registry_test.dart
            # keeps it equal to the dispatcher's match table.
            if ($env:CARGO_TARGET_DIR) {
                $exe = Join-Path $env:CARGO_TARGET_DIR 'release\mics-engine.exe'
            } else {
                $exe = Join-Path (Join-Path $repo 'engine') 'target\release\mics-engine.exe'
            }
            dart run qa\contract.dart --engine $exe
        }
        What = 'Every registered JSON-RPC method answers, or refuses, as documented'
    },
    @{
        Id   = 'update.verify'
        Tier = 'full'
        Dir  = $repo
        Run  = {
            # D-046: where `update.check` looks (environment -> saved URL -> the
            # channel's compiled-in default), that `off` really switches checking
            # off, and that a manifest which does not describe its own download is
            # refused before anything is staged. The probe serves the feed itself
            # on 127.0.0.1, so the step needs no network and no elevation, and it
            # refuses to measure a binary older than `engine\src` (D-045's lesson).
            $engineArgs = @("-NoProfile", "-ExecutionPolicy", "Bypass",
                "-File", (Join-Path $repo 'scripts\verify-update.ps1'))
            if ($env:CARGO_TARGET_DIR) {
                $engineArgs += @("-EngineExe", (Join-Path $env:CARGO_TARGET_DIR 'release\mics-engine.exe'))
            }
            powershell @engineArgs
            if ($LASTEXITCODE -ne 0) { throw "verify-update.ps1 exited $LASTEXITCODE" }
        }
        What = 'update.check reads the channel''s own feed, obeys off, and refuses a manifest that fails its hash'
    },
    @{
        Id   = 'app.build'
        Tier = 'full'
        Dir  = $repo
        Run  = { flutter build windows --release }
        What = 'Release build of the Windows app'
    },
    @{
        Id   = 'opsec.verify'
        Tier = 'release'
        Dir  = $repo
        Run  = {
            # The shipped bytes, not the build flags: does the package name the
            # account that built it, and did any counted fingerprint grow past
            # `qa\opsec-baseline.json`? It reads `dist\MICS-portable`, the folder
            # `make-release.ps1` assembles (and gates on the same probe), so this
            # verifies the artifact - package first, then `-Tier release`.
            powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $repo 'scripts\verify-opsec.ps1')
        }
        What = 'The packaged files carry no build fingerprint the baseline forbids'
    },
    @{
        Id   = 'manifest.verify'
        Tier = 'release'
        Dir  = $repo
        Run  = {
            # The package's own description of itself (c2/D-025): the manifest is an
            # RT_RCDATA resource inside `mics-engine.exe`, and this reads it back
            # out of the packaged engine and re-hashes every file it lists. A
            # package that no longer matches what its signed manifest says - a
            # changed file, a swapped DLL, a re-packed folder - fails here.
            powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $repo 'scripts\verify-manifest.ps1')
        }
        What = 'The packaged engine carries a manifest that describes the package'
    },
    @{
        Id   = 'tamper.verify'
        Tier = 'release'
        Dir  = $repo
        Run  = {
            # The adversarial half of the manifest (t2): one thing tampered with at a
            # time in a private copy - a byte flipped in each shipped binary, a
            # same-size swapped DLL, an edited manifest, the manifest copied into an
            # unsigned engine, a copied install - and both halves asked: the gate
            # above must refuse it and the packaged engine must report it in
            # `status.integrity`. The published package is the control.
            powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $repo 'scripts\verify-tamper.ps1')
        }
        What = 'A tampered copy of the package is refused by the gate and reported by the engine'
    }
)

$selected = @($steps | Where-Object {
        $tierRank[$_.Tier] -le $limit -and ($Only -eq '' -or $_.Id -like $Only)
    })

if ($selected.Count -eq 0) {
    throw "no step matches tier '$Tier' and filter '$Only'"
}

if ($List) {
    foreach ($step in $selected) {
        Write-Output ("  {0,-16} {1,-8} {2}" -f $step.Id, $step.Tier, $step.What)
    }
    exit 0
}

# ------------------------------------------------------------------ the runner

$results = New-Object System.Collections.ArrayList
$failed = $null
$index = 0

foreach ($step in $selected) {
    $index++
    Write-Output ''
    Write-Output ("==> [{0}/{1}] {2} - {3}" -f $index, $selected.Count, $step.Id, $step.What)
    $watch = [System.Diagnostics.Stopwatch]::StartNew()
    $ok = $true
    $detail = ''
    Push-Location $step.Dir
    # A native command writes its progress to stderr (cargo's "Finished ... in
    # 2.0s"), and under `Stop` PowerShell 5.1 turns that into a terminating
    # error - trap 8 in docs/TODO.md. The exit code is the verdict here, not the
    # shape of the output stream.
    $previousPolicy = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        & $step.Run
        if ($LASTEXITCODE -ne 0) {
            $ok = $false
            $detail = "exit code $LASTEXITCODE"
        }
    } catch {
        $ok = $false
        $detail = $_.Exception.Message
    } finally {
        $ErrorActionPreference = $previousPolicy
        Pop-Location
        $watch.Stop()
    }

    [void]$results.Add([ordered]@{
            id      = $step.Id
            tier    = $step.Tier
            ok      = $ok
            seconds = [math]::Round($watch.Elapsed.TotalSeconds, 1)
            detail  = $detail
        })

    if ($ok) {
        Write-Output ("    PASS ({0:n1}s)" -f $watch.Elapsed.TotalSeconds)
    } else {
        Write-Output ("    FAIL ({0:n1}s): {1}" -f $watch.Elapsed.TotalSeconds, $detail)
        $failed = $step
        break
    }
}

# ------------------------------------------------------------------- the report

$reportDir = Join-Path $repo 'build'
if (-not (Test-Path $reportDir)) {
    New-Item -ItemType Directory -Path $reportDir | Out-Null
}
$reportPath = Join-Path $reportDir ("pipeline-{0}.json" -f $Tier)
[ordered]@{
    tier    = $Tier
    head    = $head
    when    = (Get-Date).ToString('o')
    ok      = ($null -eq $failed)
    results = $results
} | ConvertTo-Json -Depth 5 | Set-Content -Path $reportPath -Encoding UTF8

Write-Output ''
if ($null -ne $failed) {
    Write-Output ("RESULT: FAIL - {0} ({1})" -f $failed.Id, $failed.What)
    Write-Output ("report: {0}" -f $reportPath)
    exit 1
}

$totalSeconds = 0.0
foreach ($result in $results) { $totalSeconds += $result['seconds'] }

Write-Output ("RESULT: PASS - {0} step(s), {1:n1}s total" -f $results.Count, $totalSeconds)
Write-Output ("report: {0}" -f $reportPath)
exit 0